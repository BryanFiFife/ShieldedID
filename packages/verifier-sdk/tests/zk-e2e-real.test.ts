  async function generateKeyPair() {
    return globalThis.crypto.subtle.generateKey(
      { name: "ECDSA", namedCurve: "P-256" },
      true,
      ["sign", "verify"]
    );
  }

  async function signPayload(privateKey: CryptoKey, payload: unknown) {
    const data = new TextEncoder().encode(stableStringify(payload));
    const signature = await globalThis.crypto.subtle.sign(
      { name: "ECDSA", hash: "SHA-256" },
      privateKey,
      data
    );
    return Buffer.from(signature).toString("base64");
  }

  // Mock dynamic ZK proof generation with real circuit commitment
  function mockRealZKProof(age: number, requestedThreshold: number) {
    // Simulate a real Bulletproofs proof with:
    // 1. Commitment to private age value
    // 2. Range proof that age is within valid bounds
    // 3. Challenge-response proof of knowledge

    const timestamp = Date.now();
    
    // Generate commitment: H(age || timestamp || randomness)
    const commitment = Buffer.from(
      `commitment:${age}:${timestamp}:${Math.random().toString(36).slice(2)}`
    ).toString("base64");

    // Create a mock proof that would be generated by the WASM module
    // In production, this would be actual Ristretto255 group elements
    const proof = {
      commitment, // Pedersen commitment to age
      ageInRange: age >= 18 && age <= 150, // Range proof outcome
      threshold: requestedThreshold, // The threshold being proven
      timestamp,
      // Proof of knowledge (simplified for testing)
      proofOfKnowledge: Buffer.from(`pok:${age}:${timestamp}`).toString("base64")
    };

    return proof;
  }
