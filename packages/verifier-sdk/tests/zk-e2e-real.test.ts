  it("should verify multiple ZK proofs in sequence without interference", async () => {
    // Test that real ZK proof verification doesn't have state leakage
    
    const { publicKey: pk1, privateKey: sk1 } = await generateKeyPair();
    const { publicKey: pk2, privateKey: sk2 } = await generateKeyPair();
    
    const jwk1 = (await globalThis.crypto.subtle.exportKey("jwk", pk1)) as JsonWebKey;
    const jwk2 = (await globalThis.crypto.subtle.exportKey("jwk", pk2)) as JsonWebKey;

    const verifier = new ShieldedVerifier({
      origin: "https://shop.example",
      registryUrl: "https://registry.example"
    });

    // First proof: age 25
    const pr1 = verifier.createProofRequest({
      requestedClaims: [{ type: "AGE_OVER", threshold: 18 }],
      policy: { requireStatusCheck: true, maxAgeSeconds: 60 },
      callback: { method: "POST", url: "https://shop.example/callback" }
    });

    const proof1 = mockRealZKProof(25, 18);
    const sig1 = await signPayload(sk1, { requestId: pr1.requestId, age: 25 });

    const resp1 = {
      requestId: pr1.requestId,
      walletId: "wallet-1",
      keyId: "key-1",
      publicKey: jwk1,
      suite: "ECDSA_P256_SHA256_1.0.0",
      zkProof: { ...proof1, algorithm: "BULLETPROOFS_RISTRETTO255" },
      signature: sig1,
      timestamp: new Date().toISOString()
    };

    // Second proof: age 17 (should fail)
    const pr2 = verifier.createProofRequest({
      requestedClaims: [{ type: "AGE_OVER", threshold: 21 }],
      policy: { requireStatusCheck: true, maxAgeSeconds: 60 },
      callback: { method: "POST", url: "https://shop.example/callback" }
    });

    const proof2 = mockRealZKProof(17, 21);
    const sig2 = await signPayload(sk2, { requestId: pr2.requestId, age: 17 });

    const resp2 = {
      requestId: pr2.requestId,
      walletId: "wallet-1",
      keyId: "key-2",
      publicKey: jwk2,
      suite: "ECDSA_P256_SHA256_1.0.0",
      zkProof: { ...proof2, algorithm: "BULLETPROOFS_RISTRETTO255" },
      signature: sig2,
      timestamp: new Date().toISOString()
    };

    const result1 = await verifier.verifyProof(resp1);
    const result2 = await verifier.verifyProof(resp2);

    // First should pass, second should fail (no state interference)
    expect(result1.verified).toBe(true);
    expect(result2.verified).toBe(false);
  });
